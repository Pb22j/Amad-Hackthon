type LanguageContextValue = {
  lang: Lang;
  dir: "ltr" | "rtl";
  setLang: (lang: Lang) => void;
  toggleLang: () => void;
  t: (key: string, variables?: Record<string, string>) => string;
  money: (value: number) => string;
  date: (value: string | Date) => string;
  localize: (english: string, arabic: string) => string;
};

const LanguageContext = React.createContext<LanguageContextValue | null>(null);

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = React.useState<Lang>("en");

  React.useEffect(() => {
    try {
      const stored = window.localStorage.getItem("nafi.language");
      if (stored === "ar" || stored === "en") setLangState(stored);
    } catch {
      // Continue with the default language when storage is unavailable.
    }
  }, []);

  const setLang = React.useCallback((next: Lang) => {
    setLangState(next);
    try {
      window.localStorage.setItem("nafi.language", next);
    } catch {
      // The current page can still switch languages without persistence.
    }
  }, []);

  const value = React.useMemo<LanguageContextValue>(() => {
    const dictionary = lang === "ar" ? ar : en;
    const locale = lang === "ar" ? "ar-SA" : "en-SA";
    return {
      lang,
      dir: lang === "ar" ? "rtl" : "ltr",
      setLang,
      toggleLang: () => setLang(lang === "ar" ? "en" : "ar"),
      t: (key, variables) => {
        let result = dictionary[key] ?? en[key] ?? key;
        for (const [name, replacement] of Object.entries(variables ?? {})) {
          result = result.replaceAll(`{${name}}`, replacement);
        }
        return result;
      },
      money: (value) =>
        new Intl.NumberFormat(locale, {
          style: "currency",
          currency: "SAR",
          maximumFractionDigits: 2,
        }).format(value),
      date: (value) =>
        new Intl.DateTimeFormat(locale, { month: "short", day: "numeric" }).format(
          typeof value === "string" ? new Date(value) : value
        ),
      localize: (english, arabic) => (lang === "ar" ? arabic || english : english || arabic),
    };
  }, [lang, setLang]);

  React.useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = value.dir;
  }, [lang, value.dir]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLang() {
  const context = React.useContext(LanguageContext);
  if (!context) throw new Error("useLang must be used within LanguageProvider");
  return context;
}
